using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Newtonsoft.Json.Linq;
using TrelamiumIII.Content.DevTools.VfxLab.Recipes;

namespace TrelamiumIII.Content.DevTools.VfxLab.Generation;

/// <param name="Where"> The recipe stage it's about, or the recipe's name. </param>
/// <param name="IsError"> Errors stop the shader being generated. Warnings say a value was ignored. </param>
internal readonly record struct GenerationProblem(string Where, string Message, bool IsError)
{
    public override string ToString() => $"{(IsError ? "error" : "warning")} in {Where}: {Message}";
}

/// <summary> One value for the effect, by the name it has in the generated source. </summary>
/// <param name="Values"> The numbers for a numeric kind. </param>
/// <param name="Texture"> The texture for a <see cref="ParamKind.Noise" />. </param>
internal readonly record struct UniformValue(string Name, ParamKind Kind, float[] Values, string? Texture);

/// <param name="Source"> Null when an error stopped generation. Holds no uniform values, so a recipe that differs only in those generates the same source and needs no recompile. </param>
/// <param name="SamplerCount"> Against the limit of sixteen a pass can bind. </param>
internal sealed record GeneratedShader(string? Source, IReadOnlyList<UniformValue> Uniforms, IReadOnlyList<GenerationProblem> Problems, int SamplerCount)
{
    public bool Succeeded => Source is not null;
}

/// <summary>
///     Turns a recipe into one self-contained <c>.fx</c>: the shared code, the host's template, and an instance of each stage,
///     with <c>#line</c> directives so a compile error names the stage file it came from.
/// </summary>
/// <remarks>
///     Flattened rather than <c>#include</c>-ing the library, so editing a stage can't silently change a shader that already
///     shipped. Pure string work, so it runs without the game.
/// </remarks>
internal static class ShaderGenerator
{
    /// <summary> What one pass can bind. </summary>
    public const int MaxSamplers = 16;

    private static readonly Regex IdPattern = new("^[A-Za-z][A-Za-z0-9]*$", RegexOptions.Compiled);

    public static GeneratedShader Generate(VfxRecipe recipe, StageLibrary library)
    {
        List<GenerationProblem> problems = [];

        void Error(string where, string message) => problems.Add(new GenerationProblem(where, message, true));

        if (!library.Hosts.TryGetValue(recipe.Surface, out HostDefinition? host))
        {
            Error(recipe.Name, $"there's no surface called '{recipe.Surface}'.");
            return new GeneratedShader(null, [], problems, 0);
        }

        HashSet<string> ids = new(StringComparer.Ordinal);
        List<(RecipeStage Instance, StageDefinition Definition)> active = [];

        foreach (RecipeStage instance in recipe.Stages)
        {
            if (!IdPattern.IsMatch(instance.Id))
                Error(instance.Id, "an id has to be letters and digits, starting with a letter.");
            else if (!ids.Add(instance.Id))
                Error(instance.Id, "another stage in this recipe has that id.");

            if (!library.Stages.TryGetValue(instance.Type, out StageDefinition? definition))
            {
                Error(instance.Id, $"there's no stage called '{instance.Type}'.");
                continue;
            }

            foreach (string need in definition.Needs.Where(need => !host.Provides.Contains(need)))
                Error(instance.Id, $"{definition.Name} needs {need}, which the {host.Name} surface doesn't have.");

            if (instance.Enabled)
                active.Add((instance, definition));
        }

        List<UniformValue> uniforms = [];
        var declarations = new StringBuilder();
        var calls = new StringBuilder();
        int samplers = host.SamplerCount;

        // Stable, so stages within a phase keep the recipe's order.
        foreach ((RecipeStage instance, StageDefinition definition) in active.OrderBy(static stage => stage.Definition.Phase))
        {
            samplers += definition.Params.Count(static parameter => parameter.Kind == ParamKind.Noise);
            AppendStage(declarations, instance, definition, uniforms, problems);
            calls.Append("    ").Append(instance.Id).Append('_').Append(StageParser.StageToken).Append("(px);\n");
        }

        if (samplers > MaxSamplers)
            Error(recipe.Name, $"this stack needs {samplers} textures and a pass can bind {MaxSamplers}.");

        if (problems.Any(static problem => problem.IsError))
            return new GeneratedShader(null, uniforms, problems, samplers);

        var source = new StringBuilder();

        source.Append("// Generated by the VFX Lab from the recipe ").Append(recipe.Name).Append(". Re-export the recipe instead of editing this file.\n\n");
        AppendSegment(source, library.CommonSource, 1, library.Common);
        AppendSegment(source, host.Source, host.BeforeLine, host.Before);
        source.Append(declarations);
        AppendSegment(source, host.Source, host.BetweenLine, host.Between);
        source.Append(calls);
        AppendSegment(source, host.Source, host.AfterLine, host.After);

        return new GeneratedShader(source.ToString(), uniforms, problems, samplers);
    }

    /// <summary> What a stage's numeric parameter currently holds: its value if it has a good one, else the default. For the inspector. </summary>
    /// <returns> A copy, as the inspector edits what it's given, and the default array is shared by every use of the stage. </returns>
    public static float[] NumbersOf(RecipeStage instance, ParamDefinition parameter)
    {
        instance.Values.TryGetValue(parameter.Name, out JToken? value);

        if (parameter.Kind == ParamKind.Int)
            return [ResolveInt(instance.Id, parameter, value, [])];

        return (float[])ResolveNumbers(instance.Id, parameter, value, []).Clone();
    }

    /// <summary> What a stage's texture parameter currently holds. </summary>
    public static string? TextureOf(RecipeStage instance, ParamDefinition parameter)
    {
        instance.Values.TryGetValue(parameter.Name, out JToken? value);

        return ResolveTexture(instance.Id, parameter, value, []);
    }

    private static void AppendSegment(StringBuilder output, string source, int line, string text)
    {
        output.Append("#line ").Append(line).Append(" \"").Append(source).Append("\"\n");
        output.Append(text).Append('\n');
    }

    private static void AppendStage(StringBuilder output, RecipeStage instance, StageDefinition definition, List<UniformValue> uniforms, List<GenerationProblem> problems)
    {
        string id = instance.Id;
        Dictionary<string, string> tokens = new(StringComparer.Ordinal) { [StageParser.StageToken] = $"{id}_{StageParser.StageToken}" };

        foreach (string key in instance.Values.Keys.Where(key => definition.Params.All(parameter => parameter.Name != key)))
            problems.Add(new GenerationProblem(id, $"{definition.Name} has no parameter called '{key}', so it was ignored.", false));

        output.Append("\n// ").Append(id).Append(": ").Append(definition.Name).Append('\n');

        foreach (ParamDefinition parameter in definition.Params)
        {
            string name = $"{id}_{parameter.Name}";
            instance.Values.TryGetValue(parameter.Name, out JToken? value);

            switch (parameter.Kind)
            {
                case ParamKind.Int:
                    tokens[parameter.Name] = ResolveInt(id, parameter, value, problems).ToString(CultureInfo.InvariantCulture);
                    break;
                case ParamKind.Noise:
                    string texture = $"{name}Tex";

                    output.Append("texture2D ").Append(texture).Append(";\n");
                    output.Append("sampler2D ").Append(name).Append(" = sampler_state { Texture = <").Append(texture).Append(">; AddressU = Wrap; AddressV = Wrap; MinFilter = Linear; MagFilter = Linear; };\n");

                    uniforms.Add(new UniformValue(texture, ParamKind.Noise, [], ResolveTexture(id, parameter, value, problems)));
                    tokens[parameter.Name] = name;
                    break;
                default:
                    string type = parameter.Kind switch
                    {
                        ParamKind.Float => "float",
                        ParamKind.Float2 => "float2",
                        _ => "float3",
                    };

                    output.Append(type).Append(' ').Append(name).Append(";\n");

                    uniforms.Add(new UniformValue(name, parameter.Kind, ResolveNumbers(id, parameter, value, problems), null));
                    tokens[parameter.Name] = name;
                    break;
            }
        }

        output.Append("#line ").Append(definition.BodyLine).Append(" \"").Append(definition.Source).Append("\"\n");
        output.Append(StageParser.ReplaceTokens(definition.Body, token => tokens[token])).Append('\n');
    }

    private static int ResolveInt(string id, ParamDefinition parameter, JToken? value, List<GenerationProblem> problems)
    {
        int result = (int)parameter.Default[0];

        if (value is { Type: JTokenType.Integer })
            result = value.Value<int>();
        else if (value is not null)
            Wrong(id, parameter, "a whole number", problems);

        // A loop in the shader, so unlike a slider's range this one is enforced.
        int clamped = (int)Math.Clamp(result, parameter.Min, parameter.Max);

        if (clamped != result)
            problems.Add(new GenerationProblem(id, $"{parameter.Name} of {result} is outside {parameter.Min}..{parameter.Max}, so it's {clamped}.", false));

        return clamped;
    }

    private static string? ResolveTexture(string id, ParamDefinition parameter, JToken? value, List<GenerationProblem> problems)
    {
        if (value is null)
            return parameter.DefaultTexture;

        if (value.Type == JTokenType.String)
            return value.Value<string>();

        Wrong(id, parameter, "a texture name", problems);
        return parameter.DefaultTexture;
    }

    private static float[] ResolveNumbers(string id, ParamDefinition parameter, JToken? value, List<GenerationProblem> problems)
    {
        if (value is null)
            return parameter.Default;

        if (TryNumbers(value, parameter.Default.Length, parameter.Kind == ParamKind.Color, out float[] numbers))
            return numbers;

        Wrong(id, parameter, parameter.Kind switch
        {
            ParamKind.Float => "a number",
            ParamKind.Float2 => "two numbers",
            _ => "three numbers or #rrggbb",
        }, problems);

        return parameter.Default;
    }

    private static void Wrong(string id, ParamDefinition parameter, string expected, List<GenerationProblem> problems)
        => problems.Add(new GenerationProblem(id, $"{parameter.Name} should be {expected}, so the default was used.", false));

    private static bool TryNumbers(JToken value, int count, bool allowHex, out float[] numbers)
    {
        numbers = [];

        switch (value)
        {
            case JValue { Type: JTokenType.Integer or JTokenType.Float } number when count == 1:
                numbers = [number.Value<float>()];
                return true;

            case JArray array when array.Count == count && array.All(static item => item.Type is JTokenType.Integer or JTokenType.Float):
                numbers = array.Select(static item => item.Value<float>()).ToArray();
                return true;

            case JValue { Type: JTokenType.String } text when allowHex:
                return TryHex(text.Value<string>()!, out numbers);

            default:
                return false;
        }
    }

    private static bool TryHex(string text, out float[] numbers)
    {
        numbers = [];

        if (text.Length != 7 || text[0] != '#' || !int.TryParse(text.AsSpan(1), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out int rgb))
            return false;

        numbers = [((rgb >> 16) & 255) / 255f, ((rgb >> 8) & 255) / 255f, (rgb & 255) / 255f];
        return true;
    }
}
